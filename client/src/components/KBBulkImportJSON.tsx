import { useState } from 'react';
import { Button } from '@/components/ui/button';
import { Textarea } from '@/components/ui/textarea';
import { trpc } from '@/lib/trpc';
import { toast } from 'sonner';
import {
  Dialog,
  DialogContent,
  DialogHeader,
  DialogTitle,
  DialogFooter,
  DialogDescription,
} from '@/components/ui/dialog';
import { Upload, AlertCircle, CheckCircle2, Loader2, FileJson } from 'lucide-react';

interface ImportArticle {
  title: string;
  content: string;
  category: string;
  tags?: string;
  isPublished?: boolean;
  syncSource?: string;
}

interface KBBulkImportJSONProps {
  onSuccess?: () => void;
}

export function KBBulkImportJSON({ onSuccess }: KBBulkImportJSONProps) {
  const [isOpen, setIsOpen] = useState(false);
  const [jsonText, setJsonText] = useState('');
  const [parseError, setParseError] = useState('');
  const [previewCount, setPreviewCount] = useState<number | null>(null);
  const [result, setResult] = useState<{ inserted: number; errors: string[] } | null>(null);

  const bulkCreateMutation = trpc.kb.bulkCreate.useMutation({
    onSuccess: (data) => {
      setResult(data);
      toast.success(`✅ Imported ${data.inserted} articles successfully!`);
      if (data.errors.length > 0) {
        toast.warning(`${data.errors.length} articles had errors — see details below.`);
      }
      onSuccess?.();
    },
    onError: (error) => {
      toast.error(`❌ Import failed: ${error.message}`);
    },
  });

  const handleJsonChange = (text: string) => {
    setJsonText(text);
    setParseError('');
    setPreviewCount(null);
    setResult(null);

    if (!text.trim()) return;

    try {
      const parsed = JSON.parse(text);
      if (!Array.isArray(parsed)) {
        setParseError('JSON must be an array of article objects: [ {...}, {...} ]');
        return;
      }
      if (parsed.length === 0) {
        setParseError('Array is empty — no articles to import.');
        return;
      }
      // Validate first item has required fields
      const first = parsed[0];
      if (!first.title || !first.content || !first.category) {
        setParseError('Each article must have: title, content, category fields.');
        return;
      }
      setPreviewCount(parsed.length);
    } catch (e: any) {
      setParseError(`Invalid JSON: ${e.message}`);
    }
  };

  const handleImport = () => {
    if (!jsonText.trim() || parseError || previewCount === null) return;

    try {
      const parsed: ImportArticle[] = JSON.parse(jsonText);
      const articles = parsed.map((a) => ({
        title: a.title,
        content: a.content,
        category: a.category,
        tags: a.tags || '',
        isPublished: a.isPublished !== false, // default true
        syncSource: a.syncSource || 'manual',
      }));
      bulkCreateMutation.mutate({ articles });
    } catch (e: any) {
      toast.error(`Parse error: ${e.message}`);
    }
  };

  const handleClose = () => {
    setIsOpen(false);
    setJsonText('');
    setParseError('');
    setPreviewCount(null);
    setResult(null);
  };

  return (
    <>
      <Button
        onClick={() => setIsOpen(true)}
        variant="outline"
        className="border-cyan-700 text-cyan-400 hover:bg-cyan-900/20 hover:border-cyan-500"
      >
        <FileJson className="w-4 h-4 mr-2" />
        JSON Bulk Import
      </Button>

      <Dialog open={isOpen} onOpenChange={(open) => !open && handleClose()}>
        <DialogContent className="bg-slate-900 border-slate-700 text-white max-w-2xl max-h-[90vh] overflow-y-auto">
          <DialogHeader>
            <DialogTitle className="text-xl font-bold text-white flex items-center gap-2">
              <Upload className="w-5 h-5 text-cyan-400" />
              JSON Bulk Import
            </DialogTitle>
            <DialogDescription className="text-gray-400">
              Paste a JSON array of articles generated by the media agent. Each article must have{' '}
              <code className="text-cyan-400 text-xs bg-slate-800 px-1 rounded">title</code>,{' '}
              <code className="text-cyan-400 text-xs bg-slate-800 px-1 rounded">content</code>, and{' '}
              <code className="text-cyan-400 text-xs bg-slate-800 px-1 rounded">category</code>.
            </DialogDescription>
          </DialogHeader>

          <div className="space-y-4 py-2">
            {/* Format hint */}
            <div className="rounded-lg bg-slate-800/60 border border-slate-700 p-3 text-xs text-gray-400 font-mono">
              <p className="text-cyan-400 mb-1 font-semibold">Expected format:</p>
              <pre className="whitespace-pre-wrap">{`[
  {
    "title": "Article Title",
    "content": "# Article Title\\n\\n## What's Happening?...",
    "category": "Tier 1 - Hardware & Peripherals",
    "tags": "printer,driver,windows",
    "isPublished": true,
    "syncSource": "manual"
  },
  ...
]`}</pre>
            </div>

            {/* Textarea */}
            <div>
              <Textarea
                value={jsonText}
                onChange={(e) => handleJsonChange(e.target.value)}
                placeholder="Paste your JSON array here..."
                className="bg-slate-800 border-slate-600 text-white placeholder-gray-500 font-mono text-xs min-h-[240px]"
              />
            </div>

            {/* Parse error */}
            {parseError && (
              <div className="flex items-start gap-2 rounded-lg bg-red-900/20 border border-red-500/30 p-3">
                <AlertCircle className="w-4 h-4 text-red-400 mt-0.5 flex-shrink-0" />
                <p className="text-sm text-red-300">{parseError}</p>
              </div>
            )}

            {/* Preview count */}
            {previewCount !== null && !parseError && !result && (
              <div className="flex items-center gap-2 rounded-lg bg-cyan-900/20 border border-cyan-500/30 p-3">
                <CheckCircle2 className="w-4 h-4 text-cyan-400 flex-shrink-0" />
                <p className="text-sm text-cyan-300">
                  <strong>{previewCount} articles</strong> ready to import. Click Import to proceed.
                </p>
              </div>
            )}

            {/* Result */}
            {result && (
              <div className="space-y-2">
                <div className="flex items-start gap-2 rounded-lg bg-green-900/20 border border-green-500/30 p-3">
                  <CheckCircle2 className="w-4 h-4 text-green-400 mt-0.5 flex-shrink-0" />
                  <div className="text-sm text-green-300">
                    <p className="font-semibold">Import complete!</p>
                    <p>{result.inserted} articles imported successfully.</p>
                  </div>
                </div>
                {result.errors.length > 0 && (
                  <div className="rounded-lg bg-yellow-900/20 border border-yellow-500/30 p-3">
                    <p className="text-sm text-yellow-300 font-semibold mb-1">
                      {result.errors.length} errors:
                    </p>
                    <ul className="text-xs text-yellow-400 space-y-0.5 max-h-32 overflow-y-auto">
                      {result.errors.map((err, i) => (
                        <li key={i}>• {err}</li>
                      ))}
                    </ul>
                  </div>
                )}
              </div>
            )}
          </div>

          <DialogFooter className="gap-2">
            <Button
              variant="outline"
              onClick={handleClose}
              className="border-slate-600 text-gray-400 hover:text-white"
            >
              {result ? 'Close' : 'Cancel'}
            </Button>
            {!result && (
              <Button
                onClick={handleImport}
                disabled={!previewCount || !!parseError || bulkCreateMutation.isPending}
                className="bg-cyan-600 hover:bg-cyan-700 text-white"
              >
                {bulkCreateMutation.isPending ? (
                  <>
                    <Loader2 className="w-4 h-4 mr-2 animate-spin" />
                    Importing...
                  </>
                ) : (
                  <>
                    <Upload className="w-4 h-4 mr-2" />
                    Import {previewCount ? `${previewCount} Articles` : 'Articles'}
                  </>
                )}
              </Button>
            )}
          </DialogFooter>
        </DialogContent>
      </Dialog>
    </>
  );
}
